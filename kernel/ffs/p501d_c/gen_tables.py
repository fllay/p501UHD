import sys, types
sys.modules["spidev"] = types.ModuleType("spidev")
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else "../../../notebooks")  # usage: gen_tables.py [notebooks dir]
import ad9361_driver as d, ad9361_synth_lut as L
o = ["// Generated by gen_tables.py from ad9361_driver.py / ad9361_synth_lut.py (vendor ad9361.c tables). Do not edit.",
     "#pragma once", "#include <stdint.h>", ""]
o.append("static const uint8_t RX_GAIN_TABLES[3][%d][3] = {" % len(d.RX_GAIN_TABLES[0]))
for t in d.RX_GAIN_TABLES:
    o.append("  {" + ", ".join("{0x%02X,0x%02X,0x%02X}" % r for r in t) + "},")
o.append("};")
o.append("static const uint8_t GM_ST_CTRL[%d] = {%s};" % (len(d.GM_ST_CTRL), ", ".join("0x%X" % v for v in d.GM_ST_CTRL)))
o.append("static const uint8_t GM_ST_GAIN[%d] = {%s};" % (len(d.GM_ST_GAIN), ", ".join("0x%X" % v for v in d.GM_ST_GAIN)))
o.append("typedef struct { uint16_t vco_mhz; uint8_t v[12]; } synth_row_t;")
names = []
for fdd in (False, True):
    for rng in (40, 60, 80):
        t = L.SYNTH_LUTS[(fdd, rng)]
        n = "SYNTH_%s_%d" % ("FDD" if fdd else "TDD", rng); names.append((fdd, rng, n, len(t)))
        o.append("static const synth_row_t %s[%d] = {" % (n, len(t)))
        o.append("  " + ",\n  ".join("{%d, {%s}}" % (r[0], ", ".join(str(x) for x in r[1:])) for r in t))
        o.append("};")
o.append("static const synth_row_t *synth_lut(uint64_t ref_hz, int fdd, int *n) {")
o.append("  int rng = ref_hz < 50000000ULL ? 40 : (ref_hz <= 70000000ULL ? 60 : 80);")
for fdd, rng, n, ln in names:
    o.append("  if (fdd == %d && rng == %d) { *n = %d; return %s; }" % (int(fdd), rng, ln, n))
o.append("  *n = 0; return 0;\n}")
open("ad9361_tables.h", "w").write("\n".join(o) + "\n")
print("ok", [ (n, ln) for _,_,n,ln in names])
